package app.messages.ui

data class EmojiEntry(val glyph: String, val name: String)

data class EmojiCategory(val name: String, val entries: List<EmojiEntry>) {
    val glyphs: List<String> get() = entries.map { it.glyph }
}

fun emojiResults(query: String, categoryIndex: Int): List<String> {
    val category = EmojiCatalog.getOrNull(categoryIndex) ?: EmojiCatalog.first()
    val q = query.trim()
    if (q.isEmpty()) return category.glyphs
    return EmojiCatalog.flatMap { group ->
        val groupHit = group.name.contains(q, ignoreCase = true)
        group.entries.filter { groupHit || it.name.contains(q, ignoreCase = true) }.map { it.glyph }
    }.distinct()
}

private fun group(name: String, vararg items: Pair<String, String>): EmojiCategory =
    EmojiCategory(name, items.map { EmojiEntry(it.first, it.second) })

